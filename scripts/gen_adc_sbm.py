def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--n", type=int, default=1000)
    parser.add_argument("--k", type=int, default=4)
    parser.add_argument("--avg_degree", type=float, default=20)
    parser.add_argument("--assortativity", type=float, default=0.8)
    parser.add_argument("--feature_dim", type=int, default=32)
    parser.add_argument("--feature_signal", type=float, default=3.0)
    parser.add_argument("--feature_std", type=float, default=1.0)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument("--prefix", type=str, default="graph")

    args = parser.parse_args()

    A, X, z = make_adc_sbm(
        n=args.n,
        k=args.k,
        avg_degree=args.avg_degree,
        assortativity=args.assortativity,
        feature_dim=args.feature_dim,
        feature_signal=args.feature_signal,
        feature_std=args.feature_std,
        seed=args.seed,
    )

    write_metis_graph(args.prefix + ".graph", A)
    write_labels(args.prefix + ".labels", z)
    write_features(args.prefix + ".features", X)


if __name__ == "__main__":
    main()