import numpy as np
import argparse


def make_adc_sbm(
    n=2000,
    k=4,
    avg_degree=20,
    assortativity=0.9,
    feature_dim=32,
    feature_signal=3.0,
    feature_std=1.0,
    seed=0,
):
    rng = np.random.RandomState(seed)

    # --- 1) graph cluster assignments ---------------------------------------
    sizes = rng.multinomial(n, [1/k] * k)
    z = np.repeat(np.arange(k), sizes)
    rng.shuffle(z)

    # --- 2) adjacency (ADC SBM) ---------------------------------------------
    d_in = avg_degree * assortativity
    d_out = avg_degree * (1 - assortativity)

    p_in = d_in / (sizes - 1)          # per-cluster
    p_out = d_out / (n - sizes)        # outside cluster
    
    A = np.zeros((n, n), dtype=np.int8)

    # fill block by block
    idx = [np.where(z == c)[0] for c in range(k)]

    for c in range(k):
        nodes = idx[c]
        m = len(nodes)
        # intra
        if m > 1:
            mask = rng.rand(m, m) < p_in[c]
            mask = np.triu(mask, 1)
            A[np.ix_(nodes, nodes)] = mask | mask.T

        # inter
        for d in range(c + 1, k):
            nodes2 = idx[d]
            m2 = len(nodes2)
            prob = p_out[c] if hasattr(p_out, "__len__") else p_out
            mask = rng.rand(m, m2) < prob
            A[np.ix_(nodes, nodes2)] = mask
            A[np.ix_(nodes2, nodes)] = mask.T

    # --- 3) features aligned with graph clusters -----------------------------
    mus = rng.randn(k, feature_dim) * feature_signal
    X = np.zeros((n, feature_dim))
    for c in range(k):
        X[z == c] = mus[c] + rng.randn(np.sum(z == c), feature_dim) * feature_std

    return A, X, z


