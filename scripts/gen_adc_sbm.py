def write_metis_graph(path, A):
    """Write adjacency matrix A in METIS .graph format."""
    n = A.shape[0]
    m = int(A.sum() // 2)
    with open(path, "w") as f:
        f.write(f"{n} {m} 0\n")
        for i in range(n):
            neigh = np.where(A[i] == 1)[0] + 1
            f.write(" ".join(map(str, neigh)) + "\n")


def write_labels(path, z):
    with open(path, "w") as f:
        for c in z:
            f.write(f"{c}\n")


def write_features(path, X):
    n, d = X.shape
    with open(path, "w") as f:
        f.write(f"{n} {d}\n")
        for i in range(n):
            f.write(" ".join(f"{x:.6f}" for x in X[i]) + "\n")


